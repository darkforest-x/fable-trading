"""Full-path figures of frozen accounts and explicitly post-hoc trade examples.

Figures never select strategy parameters. Example selection follows the study
plan (largest/smallest natural account PnL and largest giveback), and uses only
actual portfolio fills. Unseen-at-entry future bars are visibly shaded.
Execution paths are regenerated by the same frozen simulator and reconciled
to stored fills before drawing. All prices remain on a linear axis.
"""
