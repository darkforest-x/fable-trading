import argparse
import json
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.patches import Rectangle
from matplotlib import font_manager
import numpy as np
import pandas as pd

from yoyo.evaluation.spike_burst_validation import EXPERIMENT, sha
from yoyo.evaluation.spike_burst_execution import simulate_trade
from yoyo.evaluation.spike_burst_replay import features
from yoyo.evaluation.altseason_research import END, read_events


def style():
    path='/System/Library/Fonts/STHeiti Light.ttc'
    if Path(path).exists():
        font_manager.fontManager.addfont(path)
        plt.rcParams['font.family']=font_manager.FontProperties(fname=path).get_name()
    plt.rcParams.update({'axes.unicode_minus':False,'figure.facecolor':'#f6f8fa',
        'axes.facecolor':'white','axes.spines.top':False,'axes.spines.right':False,
        'axes.edgecolor':'#c4cdd3','grid.color':'#e3e9ed','grid.alpha':.8,'font.size':10})


def curves(folder,out):
    fig,axes=plt.subplots(2,2,figsize=(15,8),sharex='col',height_ratios=[2.3,1])
    for col,minutes in enumerate((60,240)):
        choices=[('burst_trail','full','爆发 V1','#008b78'),
                 ('focus_trail','full','原 IMACD 入场＋相同退出','#4e76b7'),
                 ('burst_trail','paired_actual','爆发：可配对部分','#945cc6'),
                 ('burst_trail','paired_random','对应随机对照','#8b9298')]
        for arm,account,label,color in choices:
            f=read_events(folder/'accounts'/f'combined_{minutes}_{arm}_all_assets_{account}_curve.csv.gz')
            t=f.time.dt.tz_convert('Asia/Shanghai').dt.tz_localize(None)
            axes[0,col].plot(t,100*(f.equity/100000-1),label=label,color=color,lw=1.7,
                             linestyle='--' if account!='full' else '-')
            axes[1,col].plot(t,100*f.drawdown,color=color,lw=1.4)
        axes[0,col].set_title(f'{minutes//60}H · 跨交易所同资产互斥账户',loc='left',fontweight='bold')
        axes[0,col].set_ylabel('账户累计收益 %');axes[1,col].set_ylabel('收盘权益回撤 %')
        axes[0,col].legend(fontsize=9,loc='upper left')
        for ax in axes[:,col]:ax.grid(axis='y');ax.axhline(0,color='#aeb9c2',lw=.7)
    fig.suptitle('SPIKE 强劲爆发 V1：最高浮盈之外，实际账户留下多少',x=.05,ha='left',fontsize=17,fontweight='bold')
    fig.text(.05,.02,'2026-07-10 — 09-09 UTC｜固定20bp往返成本，资金费率/真实冲击未完整覆盖｜两个周期分别建账户',color='#566571')
    fig.tight_layout(rect=[0,.05,1,.94]);p=out/'account_paths.png';fig.savefig(p,dpi=155);plt.close(fig)
    return p


def example(row,reason,out,number):
    source=pd.read_pickle(row.features_path)
    raw=source[['open','high','low','close','volume','quote_volume']]
    frame=features(raw);frame.attrs['minutes']=int(row.minutes)
    result=simulate_trade(frame,int(row.decision_i),float(row.tick),END,include_path=True)
    for key in ('entry_price','exit_price','net_r'):
        if not np.isclose(result[key],float(row[key]),rtol=1e-10,atol=1e-10):
            raise ValueError('Figure execution differs from frozen record: '+key)
    i=int(row.decision_i);j=int(row.exit_i);left=max(0,i-100);right=min(len(frame),j+25)
    f=frame.iloc[left:right];x=np.arange(left,right)
    fig,(ax,lower)=plt.subplots(2,1,figsize=(15,8),sharex=True,height_ratios=[3.2,1])
    ax.axvspan(i+.5,right-1,color='#eaf3ff',alpha=.65,label='信号后走势：当时不可见')
    widths=.65
    for k,r in zip(x,f.itertuples()):
        color='#009982' if r.close>=r.open else '#d85869'
        ax.vlines(k,r.low,r.high,color=color,lw=.7)
        ax.add_patch(Rectangle((k-widths/2,min(r.open,r.close)),widths,
                              max(abs(r.close-r.open),float(row.tick)*.1),facecolor=color,edgecolor=color,lw=.4))
    ax.plot(x,f.s20,color='#5b86b4',lw=1,label='SMA20')
    path=result['path']
    ax.step(path.bar_i,path.active_stop,where='post',color='#cc8750',lw=1.6,label='本根已生效保护')
    ax.scatter([int(row.entry_i)],[row.entry_price],marker='^',s=95,color='#007f6d',zorder=5,label='下根开盘成交')
    ax.scatter([j],[row.exit_price],marker='X',s=80,color='#ad354d',zorder=5,label='实际模拟退出')
    ax.axvline(i,color='#7b59b3',lw=1.2,ls='--')
    ax.annotate('信号收盘',xy=(i,frame.close.iloc[i]),xytext=(9,35),textcoords='offset points',color='#7144a4',arrowprops={'arrowstyle':'-','color':'#7144a4'})
    ax.set_title(f'{number:02d}  {row.venue.upper()} · {row.symbol} · {int(row.minutes)//60}H  |  {reason}',loc='left',fontweight='bold',fontsize=14)
    ax.legend(loc='upper left',fontsize=9,ncol=3);ax.grid(axis='y')
    lower.plot(x,f.md,color='#4e76b7',lw=1.6,label='IMACD')
    lower.plot(x,f.sb,color='#cb9333',lw=1.3,label='信号线')
    lower.axhline(0,color='#7f898f',lw=.8);lower.axvline(i,color='#7b59b3',ls='--',lw=1)
    lower.grid(axis='y');lower.legend(loc='upper left',fontsize=9)
    ticks=np.unique(np.linspace(left,right-1,9).astype(int));lower.set_xticks(ticks)
    lower.set_xticklabels([frame.index[k].tz_convert('Asia/Shanghai').strftime('%m-%d\n%H:%M') for k in ticks])
    ax.set_xlim(left-1,right);lower.set_xlabel('北京时间｜信号前100根＋完整成交持有段＋退出后24根（按可用数据截断）')
    meta=f'入场 {row.entry_price:.7g} → 退出 {row.exit_price:.7g}｜峰值 {row.peak_r:.2f}R｜兑现 {row.net_r:.2f}R｜单笔净涨幅 {100*row.net_return:.2f}%｜账户盈亏 ${row.realized_net_pnl:,.2f}'
    fig.text(.055,.955,meta,fontsize=10,color='#52616c')
    fig.text(.055,.018,'20bp静态成本；止损触发根不增加峰值。事后按固定规则挑选示例，不能代表全部信号成功率。',fontsize=9,color='#596874')
    fig.tight_layout(rect=[0,.035,1,.94]);p=out/f'trade_{number:02d}.png';fig.savefig(p,dpi=155);plt.close(fig)
    return p


def run(folder=EXPERIMENT/'results'):
    folder=Path(folder);out=folder/'figures'
    if out.exists():raise ValueError('Refusing frozen figure overwrite')
    # Authenticate the full dataset and account receipts before any chart reads.
    for manifest_name in ('dataset_manifest.json','validation_manifest.json'):
        manifest=json.loads((folder/manifest_name).read_text())
        for item in manifest['artifacts']:
            if sha(item['path'])!=item['sha256']:raise ValueError('Changed artifact: '+item['path'])
        for item in manifest.get('feature_sources',[]):
            if sha(item['path'])!=item['sha256']:raise ValueError('Changed feature source')
    out.mkdir();style();paths=[curves(folder,out)];examples=[];seen=set()
    for minutes in (60,240):
        p=folder/'accounts'/f'combined_{minutes}_burst_trail_all_assets_full_ledger.csv.gz'
        ledger=read_events(p)
        filled=ledger.loc[ledger.portfolio_selected.eq(True)&ledger.natural_exit.eq(True)].copy() if len(ledger) else ledger
        if filled.empty:continue
        filled['giveback']=filled.peak_r-filled.net_r
        choices=[(filled.sort_values('realized_net_pnl',ascending=False),'最大自然盈利'),
                 (filled.sort_values('realized_net_pnl'),'最大自然亏损'),
                 (filled.sort_values('giveback',ascending=False),'峰值回吐案例')]
        for pool,reason in choices:
            row=pool.iloc[0]
            if row.event_id in seen:continue
            seen.add(row.event_id)
            path=example(row,reason,out,len(examples)+1);paths.append(path)
            examples.append(dict(event_id=row.event_id,reason=reason,path=str(path.resolve()),
                symbol=row.symbol,venue=row.venue,minutes=int(row.minutes),route=row.route,
                entry_time=str(row.entry_time),exit_time=str(row.exit_time),peak_r=float(row.peak_r),
                net_r=float(row.net_r),net_return=float(row.net_return),account_pnl=float(row.realized_net_pnl)))
    result=dict(examples=examples,artifacts=[dict(path=str(p.resolve()),sha256=sha(p),size_bytes=p.stat().st_size) for p in paths])
    (folder/'figures_manifest.json').write_text(json.dumps(result,indent=2,ensure_ascii=False)+'\n')
    return result


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--results',type=Path,default=EXPERIMENT/'results')
    run(parser.parse_args().results)
